'''
用漏斗分析 每一层掉了多少人（多少次行为），转化率是多少
1. 算每个环节的转化率
2. 找**转化率最低的环节** = 流失最严重的地方
3. 定位原因，给优化建议
收藏和加购是两条并行的意向路径，不是 "先收藏再加购" 的先后关系。主漏斗走 点击→加购→支付，收藏单独对比分析。
'''

import pandas as pd
df=pd.read_csv('clean.csv')
#===========漏斗分析开始查看===============
counts=df['behavior'].value_counts()
print('每一个行为出现多少次：',df['behavior'].value_counts())
#按漏斗顺序取出数字
pv = counts['点击']
cart = counts['加购']
buy = counts['支付']
#1.加购率(点击---加购)
Add_to_cart_rate=cart/pv
#2.购买率(加购---支付)
buy_Rate=buy/cart
#3.整体转化率（点击---支付）
Overall_conversion_rate=buy/pv
#输出转化率
print(f"点击的次数为: {pv}")
print(f"加购的次数: {cart} ,加购率为:{Add_to_cart_rate*100:.2f}%")
print(f"购买的次数为: {buy},购买转化率为: {buy_Rate*100:.2f}%")
print(f"整体转化率为:{Overall_conversion_rate*100:.2f}%")
#==========================================================================
#环节	    转化率	   问题	                         优化方向
#点击→加购	5.89%	  最大流失点，94% 的点击没加购  	优化商品详情页、推荐精准度、降低加购门槛
#加购→支付	31.75%	  约 7 成加购未支付	            加购后限时券、降价提醒、购物车催付
